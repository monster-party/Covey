import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');

test('defines a menu-bar macOS host for the bundled server', () => {
  const app = read('macos/Sources/CoveyServerHost/CoveyServerApp.swift');
  const controller = read('macos/Sources/CoveyServerHost/ServerController.swift');
  const credentials = read('macos/Sources/CoveyServerHost/CredentialStore.swift');
  const onboarding = read('macos/Sources/CoveyServerHost/OnboardingView.swift');
  const menuBarIcon = read('scripts/render-macos-menu-icon.swift');
  const build = read('scripts/build-macos-app.js');

  assert.match(app, /Bundle\.main\.url\(forResource: "CoveyMenuBarTemplate"/);
  assert.match(app, /image\.isTemplate = true/);
  assert.match(app, /image\.size = NSSize\(width: 18, height: 18\)/);
  assert.match(app, /Image\(nsImage: Self\.menuBarIcon\)/);
  assert.match(menuBarIcon, /NSBitmapImageRep/);
  assert.match(build, /CoveyMenuBarTemplate\.png/);
  assert.match(app, /Open Covey/);
  assert.match(app, /Start Server/);
  assert.match(app, /Stop Server/);
  assert.match(controller, /applicationSupportDirectory/);
  assert.match(controller, /api\/health/);
  assert.match(controller, /COVEY_DATA_DIR/);
  assert.match(controller, /"COVEY_HOST": "0\.0\.0\.0"/);
  assert.match(controller, /func localIPv4Address\(\)/);
  assert.match(controller, /setString\(networkURL\.absoluteString/);
  assert.match(controller, /process\.terminationHandler/);
  assert.match(controller, /serverIsHealthy\(\)/);
  assert.match(controller, /isUsingExistingServer = true/);
  assert.match(controller, /func stopAndWait\(\) async/);
  assert.match(controller, /process\.terminate\(\)[\s\S]*?process\.isRunning/);
  assert.match(app, /Connected to an existing Covey Server/);
  assert.match(app, /await server\.stopAndWait\(\)/);
  assert.match(app, /Window\("Set up Covey Server", id: "onboarding"\)/);
  assert.match(app, /onChange\(of: server\.onboardingRequired\)/);
  assert.match(controller, /case needsSetup/);
  assert.match(controller, /guard let credentials = self\.resolvedCredentials\(\)/);
  assert.match(controller, /ICLOUD_EMAIL.*credentials\.email/s);
  assert.match(credentials, /kSecClassGenericPassword/);
  assert.match(credentials, /kSecAttrAccessibleAfterFirstUnlock/);
  assert.doesNotMatch(credentials, /UserDefaults/);
  assert.match(onboarding, /Use an app-specific password/);
  assert.match(onboarding, /SecureField\("App-specific password"/);
  assert.match(build, /Covey Server\.app/);
  assert.match(build, /CFBundleIconFile/);
  assert.match(build, /CoveyServer\.icns/);
  assert.match(build, /iconutil/);
  assert.match(build, /codesign/);
});
